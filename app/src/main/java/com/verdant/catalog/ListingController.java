package com.verdant.catalog;

import com.verdant.common.outbox.OutboxWriter;
import com.verdant.identity.SellerUserRepository;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.security.oauth2.jwt.Jwt;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.bind.annotation.*;
import org.springframework.web.multipart.MultipartFile;
import org.springframework.web.server.ResponseStatusException;
import com.verdant.catalog.mapping.ListingMappingWorker;

import java.math.BigDecimal;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.UUID;

@RestController
@RequestMapping("/v1/listings")
public class ListingController {

    /** A seller-facing subset of inventory_adjustments' full real reason vocabulary (V11) - SALE/RESERVATION_RELEASE are system-generated by the real checkout/reservation flow (InventoryService/ReservationService), not something a seller manually claims through this endpoint. */
    private static final Set<String> VALID_STOCK_ADJUST_REASONS =
        Set.of("RESTOCK", "MORTALITY", "CORRECTION", "OFFLINE_SALE");

    private final ListingRepository listings;
    private final SellerUserRepository sellerUsers;
    private final ListingImageService imageService;
    private final ListingMappingWorker mappingWorker;
    private final OutboxWriter outbox;
    private final JdbcTemplate jdbc;

    public ListingController(ListingRepository listings, SellerUserRepository sellerUsers,
                              ListingImageService imageService, ListingMappingWorker mappingWorker,
                              OutboxWriter outbox, JdbcTemplate jdbc) {
        this.listings = listings;
        this.sellerUsers = sellerUsers;
        this.imageService = imageService;
        this.mappingWorker = mappingWorker;
        this.outbox = outbox;
        this.jdbc = jdbc;
    }

    // @Transactional added here (and on updatePrice()/deactivate() below)
    // specifically because of the outbox.write() call each now makes -
    // OutboxWriter.write() is MANDATORY propagation (Week 6), meaning it
    // throws immediately if there is no already-open transaction to join.
    // Before this week nothing in this controller ever needed one: a
    // single repository save() already gets its own transaction from
    // Spring Data, but that transaction closes before control returns
    // here, so writing to the outbox afterward would join nothing.
    @Transactional
    @PostMapping
    @ResponseStatus(HttpStatus.CREATED)
    public Listing create(@AuthenticationPrincipal Jwt jwt, @RequestBody CreateListingRequest request) {
        UUID sellerId = currentSellerId(jwt);
        Listing saved = listings.save(new Listing(sellerId, request.rawTitle(), request.priceAmount()));
        mappingWorker.mapListing(saved.getId(), request.rawTitle(), null);
        outbox.write("LISTING", saved.getId(), "LISTING_CREATED", Map.of("listingId", saved.getId().toString()));
        return saved;
    }

    @GetMapping
    public List<Listing> list(@AuthenticationPrincipal Jwt jwt) {
        return listings.findBySellerId(currentSellerId(jwt));
    }

    // The ownership checks in get()/uploadImage() below look unreachable
    // for the cross-tenant case, and in practice they now are: with RLS
    // actually enforced (TenantAwareDataSource), a request scoped to the
    // caller's own tenant can no longer see another seller's row at all,
    // so findById() already returns empty and 404s before either check
    // runs. Left in place anyway as real defense in depth - the correct
    // behavior if RLS is ever misconfigured, disabled per-table, or this
    // code path is ever reached over a platform-admin (unscoped)
    // connection where every row IS visible.

    @GetMapping("/{id}")
    public Listing get(@AuthenticationPrincipal Jwt jwt, @PathVariable UUID id) {
        UUID sellerId = currentSellerId(jwt);
        Listing listing = listings.findById(id)
            .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND));
        if (!listing.getSellerId().equals(sellerId)) {
            throw new ResponseStatusException(HttpStatus.FORBIDDEN, "Not your listing");
        }
        return listing;
    }

    @PostMapping("/{id}/images")
    @ResponseStatus(HttpStatus.CREATED)
    public void uploadImage(@AuthenticationPrincipal Jwt jwt, @PathVariable UUID id,
                             @RequestParam("file") MultipartFile file) {
        UUID sellerId = currentSellerId(jwt);
        Listing listing = listings.findById(id)
            .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND));
        if (!listing.getSellerId().equals(sellerId)) {
            throw new ResponseStatusException(HttpStatus.FORBIDDEN, "Not your listing");
        }
        imageService.upload(id, file);
    }

    // Neither existed before this week - a seller had no way to correct a
    // price or pull a listing down through the real API at all (the
    // underlying columns, price_amount/active, obviously already did).
    // Built now because LISTING_UPDATED/LISTING_DEACTIVATED need a real
    // producer to mean anything for the search projection pipeline
    // (Week 9), not as a general listing-management feature push.

    @Transactional
    @PatchMapping("/{id}")
    public Listing updatePrice(@AuthenticationPrincipal Jwt jwt, @PathVariable UUID id,
                                @RequestBody UpdateListingRequest request) {
        UUID sellerId = currentSellerId(jwt);
        Listing listing = listings.findById(id)
            .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND));
        if (!listing.getSellerId().equals(sellerId)) {
            throw new ResponseStatusException(HttpStatus.FORBIDDEN, "Not your listing");
        }
        listing.updatePrice(request.priceAmount());
        Listing saved = listings.save(listing);
        outbox.write("LISTING", id, "LISTING_UPDATED", Map.of("listingId", id.toString()));
        return saved;
    }

    @Transactional
    @PostMapping("/{id}/deactivate")
    public void deactivate(@AuthenticationPrincipal Jwt jwt, @PathVariable UUID id) {
        UUID sellerId = currentSellerId(jwt);
        Listing listing = listings.findById(id)
            .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND));
        if (!listing.getSellerId().equals(sellerId)) {
            throw new ResponseStatusException(HttpStatus.FORBIDDEN, "Not your listing");
        }
        listing.deactivate();
        listings.save(listing);
        outbox.write("LISTING", id, "LISTING_DEACTIVATED", Map.of("listingId", id.toString()));
    }

    /**
     * The seller app's own "Stock adjust" screen (Day 56) - one tap
     * decrement with a reason. actor_id is the real authenticated JWT
     * subject, not a generic "seller" label - inventory_adjustments (Week
     * 4) already has a real per-row actor column, previously only ever
     * populated with the literal string "system" (InventoryService's own
     * real sale-decrement path); this is the first real HUMAN actor this
     * table has ever recorded. A real DB CHECK (quantity >= 0, V11)
     * rejects a correction that would take stock negative - caught and
     * turned into a proper 409, not a raw 500.
     */
    @Transactional
    @PostMapping("/{id}/stock-adjust")
    public void adjustStock(@AuthenticationPrincipal Jwt jwt, @PathVariable UUID id,
                             @RequestBody StockAdjustRequest request) {
        UUID sellerId = currentSellerId(jwt);
        Listing listing = listings.findById(id)
            .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND));
        if (!listing.getSellerId().equals(sellerId)) {
            throw new ResponseStatusException(HttpStatus.FORBIDDEN, "Not your listing");
        }
        if (request.reason() == null || !VALID_STOCK_ADJUST_REASONS.contains(request.reason())) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST,
                "reason must be one of " + VALID_STOCK_ADJUST_REASONS);
        }

        try {
            jdbc.update("""
                INSERT INTO inventory (listing_id, quantity, buffer)
                VALUES (?, GREATEST(?, 0), 1)
                ON CONFLICT (listing_id) DO UPDATE
                    SET quantity = inventory.quantity + ?, updated_at = now()
                """, id, request.delta(), request.delta());
            jdbc.update("""
                INSERT INTO inventory_adjustments (listing_id, delta, reason, actor_id)
                VALUES (?, ?, ?, ?)
                """, id, request.delta(), request.reason(), jwt.getSubject());
        } catch (DataIntegrityViolationException e) {
            throw new ResponseStatusException(HttpStatus.CONFLICT,
                "Adjustment would take stock negative", e);
        }

        outbox.write("LISTING", id, "INVENTORY_CHANGED", Map.of("listingId", id.toString()));
    }

    private UUID currentSellerId(Jwt jwt) {
        return sellerUsers.findBySubjectId(jwt.getSubject())
            .orElseThrow(() -> new ResponseStatusException(HttpStatus.FORBIDDEN, "No seller mapped to this account"))
            .getSellerId();
    }
}
